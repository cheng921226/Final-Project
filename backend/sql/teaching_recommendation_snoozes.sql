create table if not exists public.teaching_recommendation_snoozes (
  id bigint generated by default as identity primary key,
  user_id bigint not null references public.users(id) on delete cascade,
  course_id bigint not null references public.courses(id) on delete cascade,
  recommendation_key text not null,
  snoozed_until timestamptz not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, course_id, recommendation_key)
);

create index if not exists idx_teaching_recommendation_snoozes_lookup
  on public.teaching_recommendation_snoozes (user_id, course_id, snoozed_until);

