-- Local video sources and per-student classroom-practice state.
-- Run once in the Supabase SQL editor before using these features.

alter table public.lectures
add column if not exists media_source text not null default 'youtube',
add column if not exists media_storage_path text,
add column if not exists media_mime_type text,
add column if not exists media_size_bytes bigint,
add column if not exists source_file_name text;

update public.lectures
set media_source = 'youtube'
where media_source is null;

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conname = 'lectures_media_source_check'
      and conrelid = 'public.lectures'::regclass
  ) then
    alter table public.lectures
    add constraint lectures_media_source_check
    check (media_source in ('youtube', 'upload'));
  end if;
end $$;

create table if not exists public.question_learning_states (
  id bigint generated by default as identity primary key,
  student_id bigint not null references public.users(id) on delete cascade,
  lecture_id bigint not null references public.lectures(id) on delete cascade,
  question_id bigint not null references public.questions(id) on delete cascade,
  status text not null default 'skipped',
  first_triggered_at timestamptz,
  last_skipped_at timestamptz,
  completed_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint question_learning_states_status_check
    check (status in ('skipped', 'completed')),
  constraint question_learning_states_student_question_uidx
    unique (student_id, question_id)
);

create index if not exists question_learning_states_student_lecture_idx
on public.question_learning_states (student_id, lecture_id, status);

-- Existing answers remain valid and are represented as completed states.
insert into public.question_learning_states (
  student_id, lecture_id, question_id, status, completed_at, updated_at
)
select distinct on (qa.student_id, qa.question_id)
  qa.student_id,
  qa.lecture_id,
  qa.question_id,
  'completed',
  coalesce(qa.answered_at, now()),
  now()
from public.question_attempts qa
order by qa.student_id, qa.question_id, qa.answered_at
on conflict (student_id, question_id) do update
set status = 'completed',
    completed_at = coalesce(
      public.question_learning_states.completed_at,
      excluded.completed_at
    ),
    updated_at = now();

alter table public.question_learning_states enable row level security;

-- Video objects stay private. FastAPI creates short-lived signed URLs after
-- checking the logged-in user's course access with the service-role client.
insert into storage.buckets (id, name, public)
values ('lecture-videos', 'lecture-videos', false)
on conflict (id) do update set public = false;
